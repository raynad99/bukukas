export function formatCurrency(amount: number, currency: Currency = 'IDR', lang: Language = 'id'): string {
  const config = currencySymbols[currency] || { symbol: 'Rp', position: 'prefix', space: true, name: 'Indonesian Rupiah', flag: '🇮🇩' };
  const absAmount = Math.abs(amount);
  
  let formattedNumber = '';
  if (currency === 'IDR' || currency === 'JPY' || currency === 'KRW' || currency === 'TWD') {
    formattedNumber = Math.round(absAmount).toLocaleString(lang === 'id' ? 'id-ID' : 'en-US');
  } else {
    formattedNumber = absAmount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }

  const sign = amount < 0 ? '-' : '';
  const spacer = config.space ? ' ' : '';

  if (config.position === 'prefix') {
    return `${sign}${config.symbol}${spacer}${formattedNumber}`;
  } else {
    return `${sign}${formattedNumber}${spacer}${config.symbol}`;
  }
}
